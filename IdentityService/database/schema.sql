-- IdentityService / identity_db
-- Baseline schema (0001_baseline). Applied once by database/apply-all.ps1 as role identity_svc.
-- Later changes go in migrations/NNNN_name.sql (see database/README.md).
BEGIN;

CREATE TABLE schema_migrations (
    version    varchar(100) PRIMARY KEY,
    applied_at timestamptz  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- A. ASP.NET Core Identity (Guid keys). Table names are mapped to snake_case in the DbContext.
-- ---------------------------------------------------------------------------
CREATE TABLE roles (
    id                uuid         PRIMARY KEY,
    name              varchar(256) NULL,
    normalized_name   varchar(256) NULL,
    concurrency_stamp text         NULL
);
CREATE UNIQUE INDEX ux_roles_normalized_name ON roles (normalized_name);

CREATE TABLE role_claims (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id     uuid    NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    claim_type  text    NULL,
    claim_value text    NULL,
    CONSTRAINT ux_role_claims_unique UNIQUE (role_id, claim_type, claim_value)
);

CREATE TABLE users (
    id                     uuid         PRIMARY KEY,
    user_name              varchar(256) NULL,
    normalized_user_name   varchar(256) NULL,
    email                  varchar(256) NULL,
    normalized_email       varchar(256) NULL,
    email_confirmed        boolean      NOT NULL,
    password_hash          text         NULL,
    security_stamp         text         NULL,
    concurrency_stamp      text         NULL,
    phone_number           text         NULL,
    phone_number_confirmed boolean      NOT NULL,
    two_factor_enabled     boolean      NOT NULL,
    lockout_end            timestamptz  NULL,
    lockout_enabled        boolean      NOT NULL,
    access_failed_count    integer      NOT NULL,
    created_at             timestamptz  NOT NULL DEFAULT now()   -- not in the EF model; the default fills it
);
CREATE UNIQUE INDEX ux_users_normalized_user_name ON users (normalized_user_name);
CREATE UNIQUE INDEX ux_users_normalized_email     ON users (normalized_email);

CREATE TABLE user_claims (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     uuid    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    claim_type  text    NULL,
    claim_value text    NULL
);
CREATE INDEX ix_user_claims_user_id ON user_claims (user_id);

CREATE TABLE user_logins (
    login_provider        text NOT NULL,
    provider_key          text NOT NULL,
    provider_display_name text NULL,
    user_id               uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (login_provider, provider_key)
);
CREATE INDEX ix_user_logins_user_id ON user_logins (user_id);

CREATE TABLE user_roles (
    user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id uuid NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX ix_user_roles_role_id ON user_roles (role_id);

CREATE TABLE user_tokens (
    user_id        uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    login_provider text NOT NULL,
    name           text NOT NULL,
    value          text NULL,
    PRIMARY KEY (user_id, login_provider, name)
);

-- ---------------------------------------------------------------------------
-- B. OpenIddict (library-managed; shape of OpenIddict 5.x and later).
-- These tables belong to the library. If you upgrade OpenIddict and EF reports a missing
-- column, compare against:  dotnet ef migrations script   and add a migration here.
-- ---------------------------------------------------------------------------
CREATE TABLE oidc_applications (
    id                        text         PRIMARY KEY,
    application_type          varchar(50)  NULL,
    client_id                 varchar(100) NULL,
    client_secret             text         NULL,
    client_type               varchar(50)  NULL,
    concurrency_token         varchar(50)  NULL,
    consent_type              varchar(50)  NULL,
    display_name              text         NULL,
    display_names             text         NULL,
    json_web_key_set          text         NULL,
    permissions               text         NULL,
    post_logout_redirect_uris text         NULL,
    properties                text         NULL,
    redirect_uris             text         NULL,
    requirements              text         NULL,
    settings                  text         NULL
);
CREATE UNIQUE INDEX ux_oidc_applications_client_id ON oidc_applications (client_id);

CREATE TABLE oidc_authorizations (
    id                text         PRIMARY KEY,
    application_id    text         NULL REFERENCES oidc_applications (id) ON DELETE RESTRICT,
    concurrency_token varchar(50)  NULL,
    creation_date     timestamptz  NULL,
    properties        text         NULL,
    scopes            text         NULL,
    status            varchar(50)  NULL,
    subject           varchar(400) NULL,
    type              varchar(50)  NULL
);
CREATE INDEX ix_oidc_authorizations_lookup ON oidc_authorizations (application_id, status, subject, type);

CREATE TABLE oidc_scopes (
    id                text         PRIMARY KEY,
    concurrency_token varchar(50)  NULL,
    description       text         NULL,
    descriptions      text         NULL,
    display_name      text         NULL,
    display_names     text         NULL,
    name              varchar(200) NULL,
    properties        text         NULL,
    resources         text         NULL
);
CREATE UNIQUE INDEX ux_oidc_scopes_name ON oidc_scopes (name);

CREATE TABLE oidc_tokens (
    id                text         PRIMARY KEY,
    application_id    text         NULL REFERENCES oidc_applications (id)   ON DELETE RESTRICT,
    authorization_id  text         NULL REFERENCES oidc_authorizations (id) ON DELETE RESTRICT,
    concurrency_token varchar(50)  NULL,
    creation_date     timestamptz  NULL,
    expiration_date   timestamptz  NULL,
    payload           text         NULL,
    properties        text         NULL,
    redemption_date   timestamptz  NULL,
    reference_id      varchar(100) NULL,
    status            varchar(50)  NULL,
    subject           varchar(400) NULL,
    type              varchar(50)  NULL
);
CREATE INDEX ix_oidc_tokens_lookup           ON oidc_tokens (application_id, status, subject, type);
CREATE INDEX ix_oidc_tokens_authorization_id ON oidc_tokens (authorization_id);
CREATE UNIQUE INDEX ux_oidc_tokens_reference_id ON oidc_tokens (reference_id);
CREATE INDEX ix_oidc_tokens_expiration_date  ON oidc_tokens (expiration_date);   -- for the token cleanup job

-- Transactional outbox: events are written here in the same transaction as the data change,
-- then published to RabbitMQ by the outbox worker.
CREATE TABLE outbox_messages (
    id           uuid         PRIMARY KEY,
    type         varchar(200) NOT NULL,
    payload      jsonb        NOT NULL,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    published_at timestamptz  NULL
);
CREATE INDEX ix_outbox_messages_unpublished ON outbox_messages (created_at) WHERE published_at IS NULL;

-- Inbox: remembers which messages this service already processed (idempotent consumers).
CREATE TABLE inbox_messages (
    message_id   uuid         NOT NULL,
    consumer     varchar(200) NOT NULL,
    processed_at timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (message_id, consumer)
);

INSERT INTO schema_migrations (version) VALUES ('0001_baseline');

COMMIT;
